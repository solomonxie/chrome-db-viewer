import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { expect, test } from "vitest";
import { filterHistory } from "../../src/app/conn/LeftPane";
import type { HistoryEntry } from "../../src/app/store/db";

const rows = JSON.parse(readFileSync(resolve(__dirname, "../fixtures/app/history.json"), "utf8")) as HistoryEntry[];

test("'Typed by me' hides SELECTs generated by browsing tables", () => {
  const sqls = filterHistory(rows, "typed", "").map((r) => r.id);
  expect(sqls).toEqual(["h_typed", "h_commit", "h_legacy"]);
});

test("'All' shows everything, and search applies to both", () => {
  expect(filterHistory(rows, "all", "").length).toBe(4);
  expect(filterHistory(rows, "all", "CUSTOMERS").map((r) => r.id)).toEqual(["h_browse"]);
  expect(filterHistory(rows, "typed", "customers")).toEqual([]);
});
